-- Run as the application schema owner in SQL Developer.
-- Drop existing tables manually in dependency order before re-running if needed.

CREATE TABLE COACH (
  COACH_ID          NUMBER(6) CONSTRAINT PK_COACH PRIMARY KEY,
  COACH_NAME        VARCHAR2(100) NOT NULL,
  SPECIALIZATION    VARCHAR2(80) DEFAULT 'General Fitness' NOT NULL,
  EXPERIENCE_YEARS  NUMBER(2) DEFAULT 0 NOT NULL,
  CONTACT_NO        VARCHAR2(20),
  CONSTRAINT CK_COACH_ID_POS CHECK (COACH_ID > 0),
  CONSTRAINT CK_COACH_EXP CHECK (EXPERIENCE_YEARS BETWEEN 0 AND 60),
  CONSTRAINT UQ_COACH_CONTACT UNIQUE (CONTACT_NO)
);

CREATE TABLE MEMBER (
  CARD_NO       VARCHAR2(20) CONSTRAINT PK_MEMBER PRIMARY KEY,
  MEMBER_NAME   VARCHAR2(100) NOT NULL,
  FITNESS_GOAL  VARCHAR2(40) NOT NULL,
  PHONE         VARCHAR2(20),
  JOIN_DATE     DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT CK_MEMBER_CARD CHECK (LENGTH(TRIM(CARD_NO)) > 0),
  CONSTRAINT CK_MEMBER_GOAL CHECK (
    FITNESS_GOAL IN ('Weight Loss','Muscle Gain','Strength Training',
      'General Fitness','Endurance','Fat Loss','Flexibility','Cardio Fitness')
  ),
  CONSTRAINT UQ_MEMBER_PHONE UNIQUE (PHONE)
);

-- A member has zero or one current assignment. A coach may have many.
-- CARD_NO as the assignment PK prevents a member from having multiple current coaches.
CREATE TABLE COACH_ASSIGNMENT (
  CARD_NO      VARCHAR2(20) CONSTRAINT PK_COACH_ASSIGNMENT PRIMARY KEY,
  COACH_ID     NUMBER(6) NOT NULL,
  ASSIGNED_ON  DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT FK_ASSIGN_MEMBER FOREIGN KEY (CARD_NO)
    REFERENCES MEMBER(CARD_NO) ON DELETE CASCADE,
  CONSTRAINT FK_ASSIGN_COACH FOREIGN KEY (COACH_ID)
    REFERENCES COACH(COACH_ID)
);

CREATE INDEX IX_ASSIGN_COACH ON COACH_ASSIGNMENT(COACH_ID);
CREATE INDEX IX_MEMBER_GOAL ON MEMBER(FITNESS_GOAL);
